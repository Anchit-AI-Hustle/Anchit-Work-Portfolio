// Vercel applies the headers in vercel.json; Cloudflare Workers static assets
// read a `_headers` file instead. This writes one from vercel.json so both
// hosts send the same security headers and page-specific CSPs.
// Vercel lets a later matching rule override a header; Cloudflare appends, so
// a page-specific rule first detaches the header (`! Name`) and then sets it.
// Rules this format cannot express (regex alternation, `has` conditions) are
// skipped and named, rather than written wrong.
import { readFile, writeFile } from 'node:fs/promises';

const ROOT = new URL('../', import.meta.url).pathname;
const cfg = JSON.parse(await readFile(ROOT + 'vercel.json', 'utf8'));
const out = ['# Generated by scripts/cf-headers.mjs from vercel.json. Edit vercel.json, not this file.'];
const skipped = [];
const seen = new Set();
for (const rule of cfg.headers || []) {
  if (rule.has || rule.missing) { skipped.push(rule.source); continue; }
  let src = rule.source.replace(/\/\(\.\*\)$/, '/*').replace(/\/:[A-Za-z_]+\*$/, '/*');
  if (/[()|]/.test(src) || /:[A-Za-z]/.test(src)) { skipped.push(rule.source); continue; }
  const lines = [src];
  for (const h of rule.headers) {
    if (src !== '/*' && seen.has(h.key.toLowerCase())) lines.push(`  ! ${h.key}`);
    lines.push(`  ${h.key}: ${h.value}`);
  }
  if (src === '/*') rule.headers.forEach((h) => seen.add(h.key.toLowerCase()));
  out.push(lines.join('\n'));
}
await writeFile(ROOT + 'www/_headers', out.join('\n\n') + '\n');
console.log(`[cf-headers] ${out.length - 1} rule(s) -> www/_headers` + (skipped.length ? `; skipped ${skipped.join(', ')}` : ''));
