// Cloudflare Workers serves the same www/ that Vercel does (wrangler.jsonc),
// but it never reads vercel.json. Every redirect written there, /resume, /cv,
// /amar-ujala -> /amar-ujala/study, the retired how-to and study paths, was a
// 404 on the Cloudflare host. Workers static assets read a `_redirects` file
// at the root of the assets directory instead (it is parsed, not served), so
// the build writes one from vercel.json: one source of truth, two hosts.
//
// Translation, rule by rule:
//   /x/:path*  ->  /x/*      and  :path* in the destination  ->  :splat
//   named placeholders (:collection) are the same syntax on both hosts
//   permanent true/false  ->  308 / 307, the codes Vercel itself answers with
// A rule this cannot express (a `has`/`missing` condition) is skipped and
// named, rather than written wrong.
import { readFile, writeFile } from 'node:fs/promises';

const ROOT = new URL('../', import.meta.url).pathname;
const cfg = JSON.parse(await readFile(ROOT + 'vercel.json', 'utf8'));
const lines = ['# Generated by scripts/cf-redirects.mjs from vercel.json. Edit vercel.json, not this file.'];
const skipped = [];
for (const r of cfg.redirects || []) {
  if (r.has || r.missing) { skipped.push(r.source); continue; }
  const src = r.source.replace(/\/:[A-Za-z_]+\*$/, '/*');
  const dest = r.destination.replace(/:[A-Za-z_]+\*/g, ':splat');
  if (/\s/.test(src + dest)) { skipped.push(r.source); continue; }
  lines.push(`${src} ${dest} ${r.permanent === false ? 307 : 308}`);
}
await writeFile(ROOT + 'www/_redirects', lines.join('\n') + '\n');
console.log(`[cf-redirects] ${lines.length - 1} rule(s) -> www/_redirects` + (skipped.length ? `; skipped ${skipped.join(', ')}` : ''));
